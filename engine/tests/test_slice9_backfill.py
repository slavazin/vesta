            (session,) = state.reading_back(project.context().tree)
            add_note(project, session)
            project.run("session", "close", "--session", session.id)
            project.clock.advance(seconds=60)
            out = self.start(project)
            self.assertIn("2 tasks ended without a review, and the reminder is set", out)
            self.assertIn("The owner can ask for this reminder to be turned off.", out)
