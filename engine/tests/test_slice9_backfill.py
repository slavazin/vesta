class ThroughTheBuiltCopy(unittest.TestCase):
    def setUp(self):
        self.project = Project(init=True)
        self.root = os.path.join(self.project.root, "my project")
        os.makedirs(os.path.join(self.root, "vesta"))
        shutil.copytree(BUILT, os.path.join(self.root, "vesta", ".engine"))
        self.home = Home(self.project, self.root)
        self.environment = dict(os.environ, PYTHONIOENCODING="cp1252")
        self.assertEqual(self.engine("init")[0], 0)

    def tearDown(self):
        self.home.__exit__()
        self.project.__exit__()

    def engine(self, *arguments):
        found = subprocess.run([sys.executable, os.path.join(self.root, "vesta", ".engine")] + list(arguments), capture_output=True, env=self.environment)
        return found.returncode, found.stdout.decode("cp1252", "replace"), found.stderr.decode("cp1252", "replace")

    def test_a_conversation_is_read_back_from_a_folder_with_a_space_under_another_encoding(self):
        self.home.keep("one", TALK + [said("user", "use → arrows — and “quotes”")])
        code, out, err = self.engine("walk", "backfill", "--source", "claude-code", "--conversation", "one")
        self.assertEqual(code, 0, err)
        self.assertIn("To read: 3 pieces by the owner", out)
        self.assertNotIn("did not expect", out + err)
        code, out, err = self.engine("check")
        self.assertEqual(code, 0, out + err)

    def test_several_commands_opening_one_conversation_at_once_open_one_session(self):
        self.home.keep("one", TALK)
        command = [sys.executable, os.path.join(self.root, "vesta", ".engine"), "walk", "backfill", "--source", "claude-code", "--conversation", "one"]
        running = [subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=self.environment) for _ in range(6)]
        results = [(process.communicate(), process.returncode) for process in running]
        folder = os.path.join(self.root, "vesta", ".state", "sessions")
        made = [leaf for leaf in os.listdir(folder) if leaf.endswith(".json")]
        self.assertEqual(len(made), 1, [streams[1][-200:] for streams, _ in results])
        for (out, err), code in results:
            self.assertIn(code, (0, 2), err)
            if code == 2:
                self.assertIn(b"Run this command again", err)
        self.assertGreaterEqual(len([1 for _, code in results if code == 0]), 1)


class UnreviewedReminder(unittest.TestCase):
    def left(self, project, task):
        """A task's session that ended without a review."""
        code, out, err = project.run("walk", "start", "--ask", task)
        assert code == 0, out + err
        project.clock.advance(seconds=60)
        (session,) = state.open_ones(project.context().tree)
        project.run("session", "abandon", session.id)
        project.clock.advance(seconds=60)
        return out

    def start(self, project):
        code, out, err = project.run("walk", "start", "--ask", "the next task")
        assert code == 0, out + err
        (session,) = state.open_ones(project.context().tree)
        project.run("walk", "close", "--short", "--session", session.id)
        project.run("session", "close", "--session", session.id)
        project.clock.advance(seconds=60)
        return out

    def test_the_start_sheet_says_so_at_the_count_the_configuration_sets_and_not_before(self):
        with Project(init=True, config=mtime_config()) as project, Home(project) as home:
            self.left(project, "one")
            self.assertNotIn("ended without a review, and the reminder is set", self.start(project))
            self.left(project, "two")
            out = self.start(project)
            self.assertIn("2 tasks ended without a review, and the reminder is set at 2 (`reminders.unreviewed.sessions`): `/vesta-backfill` reads", out)
            self.assertIn("that `/vesta-backfill` can read back the tasks that ended without a review", out)

    def test_reading_back_what_was_said_after_those_tasks_quiets_it_and_an_older_conversation_does_not(self):
        with Project(init=True, config=mtime_config()) as project, Home(project) as home:
            home.keep("old", TALK)
            home.keep("unrelated", [said("user", "another talk")])
            self.left(project, "one")
            self.left(project, "two")
            read_back(project, "unrelated")
            project.run("session", "abandon", state.reading_back(project.context().tree)[0].id)
            project.clock.advance(seconds=60)
            self.assertIn("2 tasks ended without a review, and the reminder is set", self.start(project))
