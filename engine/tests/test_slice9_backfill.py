def said(who, text, at="", **more):
    COUNTER[0] += 1
    entry = {"type": who, "message": {"content": text}, "uuid": "u-%04d" % COUNTER[0]}
    if at:
        entry["timestamp"] = at
    entry.update(more)
    return entry


def queued(text, mode="prompt", kind=None, **more):
    COUNTER[0] += 1
    held = {"type": "queued_command", "commandMode": mode, "prompt": text}
    if kind:
        held["origin"] = {"kind": kind}
    held.update(more)
    return {"type": "attachment", "attachment": held, "uuid": "q-%04d" % COUNTER[0], "timestamp": "2026-01-02T10:03:00Z"}


def turned_down(words):
    text = "The user doesn't want to proceed with this tool use. To tell you how to proceed, the user said:\n" + words
