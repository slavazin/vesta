class Home(object):
    """A folder that stands in for the harness's own, with this project's conversations in it."""

    def __init__(self, project, root=None):
        self.before = os.environ.get(claude_code.HOME)
        self.root = os.path.join(project.root, "the home")
        os.environ[claude_code.HOME] = self.root
        self.folder = claude_code.ClaudeCode(root or project.root).places()[-1]

    def __enter__(self):
        return self

    def __exit__(self, *_):
        if self.before is None:
            os.environ.pop(claude_code.HOME, None)
        else:
            os.environ[claude_code.HOME] = self.before

    def keep(self, name, entries, tail=""):
        path = os.path.join(self.folder, name + ".jsonl")
        support.write(path, "".join(json.dumps(entry) + "\n" for entry in entries) + tail)
        return path


def walk(project, *more):
    return project.run("walk", "backfill", *more)


def read_back(project, name="one", *more):
    code, out, err = walk(project, "--source", "claude-code", "--conversation", name, *more)
    assert code == 0, out + err
    return out


def sessions(project):
    return [session for session in state.every(project.context().tree) if session.origin]


def note(**changes):
    found = {"title": "The fetch path slept between retries", "body": "\"never sleep in the fetch path\". Read back from an earlier conversation.",
             "via": "owner-steer", "anchor": "owner, 2026-01-02", "steer-kind": "correction", "moment": "work", "missed-by": "none"}
    found.update(changes)
    return found


def add_note(project, session, **changes):
    code, out, err = project.run("obs", "add", "--session", session.id, stdin=io.StringIO(json.dumps([note(**changes)])))
    assert code == 0, out + err


def notes(project):
    return sorted(path for path in project.files("vesta/observations") if "/open/" in path)


def owner(found, conversation):
    return [turn.text for turn in found.turns(conversation) if turn.who == Turn.OWNER]


